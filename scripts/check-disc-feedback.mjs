import assert from "node:assert/strict";
import { DiscPanel } from "../src/disc-panel-mesh.ts";

const context = new Proxy({}, { get: (target, key) => target[key] ?? (() => {}), set: (target, key, value) => { target[key] = value; return true; } });
globalThis.document = { createElement: () => ({ width: 0, height: 0, getContext: () => context }) };
const panel = new DiscPanel();
const texture = panel.mesh.material.map;
const state = { title: "01 · Track", state: "Paused", playing: false, disabled: false, hover: null, pressed: null };
panel.paint(state);
const idleVersion = texture.version;
for (let frame = 0; frame < 120; frame++) panel.paint(state);
assert.equal(texture.version, idleVersion, "Idle controls do not upload a new texture each frame");
const active = { ...state, playing: true, hover: "toggle", pressed: "toggle" };
panel.paint(active);
const firstVersion = texture.version;
panel.paint(active);
assert.ok(texture.version > firstVersion, "Feedback continues between input changes");
for (let frame = 0; frame < 240; frame++) panel.paint(active);
const settledVersion = texture.version;
for (let frame = 0; frame < 120; frame++) panel.paint(active);
assert.equal(texture.version, settledVersion, "Settled feedback stops uploading textures");
panel.paint(state);
const transitioningVersion = texture.version;
panel.paint(state, 1 / 60, true);
assert.ok(texture.version > transitioningVersion, "Reduced motion paints the final state even during an existing transition");
const reducedVersion = texture.version;
panel.paint(state, 1 / 60, true);
assert.equal(texture.version, reducedVersion);
panel.dispose();
console.log("Disc feedback checks passed: animated response, settled uploads, idle uploads, reduced-motion interruption.");
